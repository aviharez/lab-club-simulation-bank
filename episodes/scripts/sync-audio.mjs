// Mirrors the approved audio library (../audio/final + audio_manifest.json) into public/audio/lib so
// staticFile() can serve it, and regenerates src/audio/library.generated.ts (the typed index).
// Run: npm run sync-audio   (after any change in ../audio/final or the manifest)
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const audio = path.resolve(root, "..", "audio");
const src = path.join(audio, "final");
const dst = path.join(root, "public", "audio", "lib");
const manifest = JSON.parse(fs.readFileSync(path.join(audio, "audio_manifest.json"), "utf8"));

// The mirror is fully derived: rebuild it so files removed from the library do not linger.
fs.rmSync(dst, { recursive: true, force: true });
fs.cpSync(src, dst, { recursive: true });
fs.copyFileSync(path.join(audio, "audio_manifest.json"), path.join(dst, "audio_manifest.json"));

const voices = {};
const sfx = {};
const music = {};
const missing = [];
for (const f of manifest.files) {
  const rel = f.file.replace(/^final\//, "");
  if (!fs.existsSync(path.join(src, rel))) missing.push(rel);
  const base = { path: rel, duration: f.duration, lufs: f.lufs, loop: Boolean(f.loop) };
  const name = path.basename(rel, ".mp3");
  if (f.type === "voice") {
    (voices[f.character] ??= {})[f.reaction] = { ...base, text: f.romaji ?? "" };
  } else if (f.type === "sfx") {
    (sfx[f.category] ??= {})[name] = base;
  } else if (f.type === "music") {
    music[name] = { ...base, ...(f.bpm ? { bpm: f.bpm, bars: f.bars } : {}) };
  } else {
    throw new Error(`unknown manifest type "${f.type}" for ${f.file}`);
  }
}
if (missing.length) throw new Error(`manifest lists files that are not in audio/final:\n  ${missing.join("\n  ")}`);

const out = `// GENERATED by scripts/sync-audio.mjs from audio/audio_manifest.json. Do not edit: run \`npm run sync-audio\`.
// Paths are relative to public/audio/lib. Durations in seconds.

export const VOICES = ${JSON.stringify(voices, null, 2)} as const;

export const SFX = ${JSON.stringify(sfx, null, 2)} as const;

export const MUSIC = ${JSON.stringify(music, null, 2)} as const;
`;
fs.mkdirSync(path.join(root, "src", "audio"), { recursive: true });
fs.writeFileSync(path.join(root, "src", "audio", "library.generated.ts"), out);

const n = (o) => Object.values(o).reduce((a, g) => a + Object.keys(g).length, 0);
console.log(`synced ${n(voices)} voices + ${n(sfx)} sfx + ${Object.keys(music).length} music -> public/audio/lib, src/audio/library.generated.ts`);
